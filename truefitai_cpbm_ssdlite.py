# Part B -- BodyShapeOptimizer  (drop-in replacement for SMPLXOptimizer)
# ==============================================================================

class BodyShapeOptimizer(nn.Module):
    """
    Fits CPBM beta parameters to 2-D MediaPipe keypoints via gradient descent.

    Drop-in replacement for SMPLXOptimizer:
      .has_real_model -- always True (no external weights needed)
      .set_shape_prior(prior)
      .fit(kpts, image_shape, height_cm, scale_cm_per_px, ...)
    """

    def __init__(self, model_dir=None, gender: str = 'neutral'):
        super().__init__()
        self.gender         = gender
        self.has_real_model = True   # always available
        self.shape_prior    = None

        self.cpbm         = ParametricBodyModel().to(DEVICE)
        self.shape_params = nn.Parameter(
            torch.zeros(1, ParametricBodyModel.N_BETAS, dtype=DTYPE, device=DEVICE))
        self.transl_2d    = nn.Parameter(torch.zeros(2, dtype=DTYPE, device=DEVICE))

        log.info('[Tier 3] CPBM ready (gender=%s, N_BETAS=%d, no weights needed).',
                 gender, ParametricBodyModel.N_BETAS)

    def set_shape_prior(self, prior):
        self.shape_prior = prior

    def _forward_body(self):
        return self.cpbm(self.shape_params)

    def _project(self, joints_3d, scale_px_m, cx, cy):
        proj_x = joints_3d[:,0] * scale_px_m + cx + self.transl_2d[0]
        proj_y = joints_3d[:,1] * -scale_px_m + cy + self.transl_2d[1]
        return torch.stack([proj_x, proj_y], dim=1)

    W_REPROJ    = 0.5
    W_STATURE   = 50.0
    W_PRIOR     = 5.0
    W_SHAPE_REG = 5.0
    BETA_CLAMP  = 3.0

    def fit(self, kpts, image_shape, height_cm, scale_cm_per_px, point_cloud_3d=None):
        if USE_HEURISTIC:
            log.info('[fit] Using heuristic mesh (USE_HEURISTIC=True).')
            return self._heuristic_mesh(height_cm), False

        H, W       = image_shape
        target_h_m = torch.tensor(height_cm/100.0, device=DEVICE, dtype=DTYPE)
        cx, cy     = W/2.0, H/2.0

        y_vals     = [kpts[k][1] for k in kpts]
        pixel_h    = max(max(y_vals) - min(y_vals), 50.0)
        scale_px_m = pixel_h / (height_cm/100.0)
        log.info('[fit] pixel_h=%.1fpx -> scale=%.1f px/m', pixel_h, scale_px_m)

        valid_pairs = [(si, mk) for si, mk in SMPLX_TO_MP.items() if mk in kpts]
        cpbm_idx    = [p[0] for p in valid_pairs]
        mp_names    = [p[1] for p in valid_pairs]
        target_xy   = torch.tensor(
            [[kpts[n][0], kpts[n][1]] for n in mp_names], dtype=DTYPE, device=DEVICE)
        joint_w = torch.tensor(
            [JOINT_CONFIDENCE.get(n, 0.5) for n in mp_names], dtype=DTYPE, device=DEVICE)
        joint_w = joint_w / joint_w.sum()

        with torch.no_grad():
            if self.shape_prior is not None and self.shape_prior.is_fitted:
                init_b = self.shape_prior.predict_betas(height_cm)
                self.shape_params.data = torch.tensor(
                    init_b[None], dtype=DTYPE, device=DEVICE)
                log.info('[fit] ANSUR beta warm-start (norm=%.3f).',
                         float(np.linalg.norm(init_b)))
            else:
                self.shape_params.data.zero_()
            beta_anchor = self.shape_params.data.clone()
            self.transl_2d.data[0] = float(np.mean([kpts[k][0] for k in kpts])) - cx
            self.transl_2d.data[1] = float(np.mean([kpts[k][1] for k in kpts])) - cy

        log.info('Stage 1/3: shape fitting (200 steps)...')
        self._optimise(torch.optim.Adam([self.shape_params], lr=0.05),
                       cpbm_idx, target_xy, joint_w, target_h_m, scale_px_m,
                       cx, cy, 200, beta_anchor, point_cloud_3d, 'S1')

        log.info('Stage 2/3: shape + translation (500 steps)...')
        self._optimise(torch.optim.Adam([self.shape_params, self.transl_2d], lr=0.01),
                       cpbm_idx, target_xy, joint_w, target_h_m, scale_px_m,
                       cx, cy, 500, beta_anchor, point_cloud_3d, 'S2')

        log.info('Stage 3/3: fine alignment (200 steps)...')
        self._optimise(torch.optim.Adam([self.shape_params, self.transl_2d], lr=0.002),
                       cpbm_idx, target_xy, joint_w, target_h_m, scale_px_m,
                       cx, cy, 200, beta_anchor, point_cloud_3d, 'S3')

        self.eval()
        with torch.no_grad():
            out   = self._forward_body()
            verts = out.vertices[0].cpu().numpy()
            faces = out.faces
        mesh = trimesh.Trimesh(verts, faces, process=False)
        h_m  = mesh.bounds[1][1] - mesh.bounds[0][1]
        if h_m > 0.01:
            mesh.apply_scale((height_cm/100.0)/h_m)
        log.info('[fit] Final mesh height=%.1f cm | beta=%s',
                 height_cm,
                 np.array2string(self.shape_params.data.cpu().numpy()[0], precision=2))
        return mesh, True

    def _optimise(self, optimizer, cpbm_idx, target_xy, joint_w,
                  target_h_m, scale_px_m, cx, cy, n_steps,
                  beta_anchor, point_cloud_3d=None, stage_label=''):
        self.train(); self.cpbm.train()
        img_diag = float((cx**2 + cy**2)**0.5)
        n_betas  = float(self.shape_params.shape[1])

        for step in range(n_steps):
            optimizer.zero_grad()
            out       = self._forward_body()
            joints_3d = out.joints[0]

            sel         = joints_3d[cpbm_idx]
            proj_2d     = self._project(sel, scale_px_m, cx, cy)
            diff_sq     = ((proj_2d - target_xy) / img_diag)**2
            loss_reproj = (joint_w * diff_sq.sum(dim=1)).sum()

            y_ext        = joints_3d[:,1].max() - joints_3d[:,1].min()
            loss_stature = (y_ext - target_h_m)**2

            loss_prior   = ((self.shape_params - beta_anchor)**2).sum() / n_betas
            excess       = F.relu(self.shape_params.abs() - self.BETA_CLAMP)
            loss_barrier = (excess**2).sum()

            loss = (self.W_REPROJ    * loss_reproj
                  + self.W_STATURE   * loss_stature
                  + self.W_PRIOR     * loss_prior
                  + self.W_SHAPE_REG * loss_barrier)

            if point_cloud_3d is not None:
                tgt_d  = torch.tensor(point_cloud_3d[:,2], dtype=DTYPE, device=DEVICE)
                mesh_z = out.vertices[0][:,2].mean()
                loss  += ((mesh_z - tgt_d.mean())**2) * 5.0

            loss.backward()
            optimizer.step()
            with torch.no_grad():
                self.shape_params.data.clamp_(-self.BETA_CLAMP, self.BETA_CLAMP)

            if step % 50 == 0 or step == n_steps-1:
                log.debug('  [%s] step %3d | reproj=%.4f stature=%.4f '
                          'prior=%.4f barrier=%.4f |b|=%.3f',
                          stage_label, step,
                          loss_reproj.item(), loss_stature.item(),
                          loss_prior.item(), loss_barrier.item(),
                          float(self.shape_params.data.norm()))

    @staticmethod
    def _heuristic_mesh(height_cm: float) -> trimesh.Trimesh:
        m = trimesh.creation.cylinder(
            radius=(height_cm * 0.16) / 100.0,
            height=height_cm / 100.0, sections=64)
        m.apply_translation([0, height_cm/200.0, 0])
        return m


