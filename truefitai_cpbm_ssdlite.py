"""## Cell 10 -- Custom Parametric Body Model (CPBM) + Optimizer

`ParametricBodyModel` is a commercially-free, analytically-generated 3-D body mesh.
No external weight files are required.

beta parameters and their physical meaning:

| idx | meaning             | reference | sensitivity |
|-----|---------------------|-----------|-------------|
|  0  | height scale        | 1.72 m    | +/-5 cm     |
|  1  | chest circumference | 0.974 m   | +/-4 cm     |
|  2  | waist circumference | 0.839 m   | +/-4 cm     |
|  3  | hip circumference   | 0.967 m   | +/-4 cm     |
|  4  | shoulder width      | 0.430 m   | +/-2 cm     |
|  5  | torso depth ratio   | 0.65      | +/-0.05     |

Joint indices match SMPLX_TO_MP so the optimizer and circumference extractor
require zero changes.

"""

import math as _math

# ==============================================================================
# Part A -- Parametric Body Model (CPBM)
# Commercially free; no weight files; geometry generated analytically.
# ==============================================================================

class _BodyModelOutput:
    """Container matching the fields expected by the rest of the pipeline."""
    def __init__(self, vertices, joints, faces):
        self.vertices = vertices   # (1, V, 3) torch tensor
        self.joints   = joints     # (1, 22, 3) torch tensor
        self.faces    = faces      # numpy int32 array (F, 3)


class ParametricBodyModel(nn.Module):
    """
    Commercially-free differentiable parametric body mesh (CPBM).
    Replaces SMPL-X: no registration, no weight files required.

    Shape parameters beta (N_BETAS = 6):
      b[0] height scale           (+/- 5 cm per unit)
      b[1] chest circumference    (+/- 4 cm circumference per unit)
      b[2] waist circumference    (+/- 4 cm circumference per unit)
      b[3] hip circumference      (+/- 4 cm circumference per unit)
      b[4] shoulder width         (+/- 2 cm per unit)
      b[5] torso depth ratio      (+/- 0.05 per unit)

    Neutral reference: ANSUR II mixed-gender median values.
    Joint layout matches SMPLX_TO_MP so the optimizer needs no changes.
    """

    N_BETAS    = 6
    N_RING_PTS = 32   # vertices per cross-section ring
    N_SLICES   = 24   # vertical cross-section slices

    # ANSUR II neutral reference (SI)
    REF_HEIGHT     = 1.720
    REF_CHEST_C    = 0.974
    REF_WAIST_C    = 0.839
    REF_HIP_C      = 0.967
    REF_SHOULDER_W = 0.430
    REF_DEPTH_R    = 0.650

    BETA_SENS = [0.05, 0.04, 0.04, 0.04, 0.02, 0.05]

    # Fraction-of-stature heights for anatomical landmarks (ANSUR II)
    F_ANKLE    = 0.040
    F_KNEE     = 0.285
    F_HIP      = 0.530
    F_WAIST    = 0.640
    F_CHEST    = 0.750
    F_SHOULDER = 0.820
    F_NECK     = 0.870
    F_CHIN     = 0.920
    F_HEAD     = 1.000

    def __init__(self):
        super().__init__()
        angles = torch.linspace(0, 2 * _math.pi, self.N_RING_PTS + 1)[:-1]
        self.register_buffer('_cos_t', torch.cos(angles))
        self.register_buffer('_sin_t', torch.sin(angles))
        self._faces_np = self._build_faces()

    def _build_faces(self):
        P, S = self.N_RING_PTS, self.N_SLICES
        faces = []
        for s in range(S - 1):
            for p in range(P):
                a = s*P + p;      b_v = s*P + (p+1)%P
                c = (s+1)*P + p;  d = (s+1)*P + (p+1)%P
                faces += [[a, b_v, d], [a, d, c]]
        top_c = S * P
        for p in range(P):
            faces.append([(S-1)*P+p, (S-1)*P+(p+1)%P, top_c])
        bot_c = S * P + 1
        for p in range(P):
            faces.append([p, bot_c, (p+1)%P])
        return np.array(faces, dtype=np.int32)

    @staticmethod
    def _ellipse_a(circ_m: float, depth_ratio: float) -> float:
        """Semi-major axis from circumference using Ramanujan 2nd approximation.
        Ellipse with semi-axes a, b=depth_ratio*a.
        C = pi * [3(a+b) - sqrt((3a+b)(a+3b))]"""
        r = depth_ratio
        factor = 3.0*(1.0+r) - _math.sqrt((3.0+r)*(1.0+3.0*r))
        return circ_m / (_math.pi * factor)

    def forward(self, betas: torch.Tensor) -> _BodyModelOutput:
        """Args: betas (1, N_BETAS). Returns _BodyModelOutput."""
        dev, dt = betas.device, betas.dtype
        b    = betas[0]
        sens = torch.tensor(self.BETA_SENS, dtype=dt, device=dev)

        height_m   = torch.clamp(self.REF_HEIGHT     + b[0]*sens[0], 1.2, 2.3)
        chest_c    = torch.clamp(self.REF_CHEST_C    + b[1]*sens[1], 0.55, 1.50)
        waist_c    = torch.clamp(self.REF_WAIST_C    + b[2]*sens[2], 0.45, 1.45)
        hip_c      = torch.clamp(self.REF_HIP_C      + b[3]*sens[3], 0.55, 1.50)
        shoulder_w = torch.clamp(self.REF_SHOULDER_W + b[4]*sens[4], 0.28, 0.60)
        depth_r    = torch.clamp(self.REF_DEPTH_R    + b[5]*sens[5], 0.40, 1.20)

        # Semi-axes from circumferences (first-order differentiable approximation)
        dr   = float(depth_r.detach())
        fact = _math.pi * (3.0*(1.0+dr) - _math.sqrt((3.0+dr)*(1.0+3.0*dr)))
        a_chest = torch.tensor(self._ellipse_a(float(chest_c.detach()), dr), dtype=dt, device=dev)                   + (chest_c - float(chest_c.detach())) / fact
        a_waist = torch.tensor(self._ellipse_a(float(waist_c.detach()), dr), dtype=dt, device=dev)                   + (waist_c - float(waist_c.detach())) / fact
        a_hip   = torch.tensor(self._ellipse_a(float(hip_c.detach()),   dr), dtype=dt, device=dev)                   + (hip_c   - float(hip_c.detach()))   / fact

        a_ankle = a_hip * 0.40
        a_knee  = a_hip * 0.55
        a_sho   = shoulder_w * 0.38
        a_neck  = torch.tensor(0.065, dtype=dt, device=dev)
        a_head  = torch.tensor(0.090, dtype=dt, device=dev)

        fracs_list = [self.F_ANKLE, self.F_KNEE, self.F_HIP,
                      0.5*(self.F_HIP+self.F_WAIST), self.F_WAIST,
                      0.5*(self.F_WAIST+self.F_CHEST), self.F_CHEST,
                      self.F_SHOULDER, self.F_NECK, self.F_CHIN, self.F_HEAD]
        fracs = torch.tensor(fracs_list, dtype=dt, device=dev)
        aa    = torch.stack([a_ankle, a_knee, a_hip, (a_hip+a_waist)/2,
                             a_waist, (a_waist+a_chest)/2, a_chest,
                             a_sho, a_neck*1.4, a_neck, a_head])

        t   = torch.linspace(fracs_list[0], fracs_list[-1], self.N_SLICES, dtype=dt, device=dev)
        idx = torch.searchsorted(fracs, t).clamp(1, len(fracs)-1)
        lo, hi  = idx-1, idx
        alpha   = (t - fracs[lo]) / (fracs[hi] - fracs[lo] + 1e-8)
        dense_a = aa[lo]*(1-alpha) + aa[hi]*alpha   # (N_SLICES,)

        y  = t * height_m                                       # (S,)
        x  = dense_a[:,None] * self._cos_t[None,:]             # (S, P)
        z  = dense_a[:,None] * depth_r * self._sin_t[None,:]   # (S, P)

        vx = x.reshape(-1)
        vy = y[:,None].expand_as(x).reshape(-1)
        vz = z.reshape(-1)

        z0    = torch.zeros(1, dtype=dt, device=dev)
        top_c = torch.stack([z0, height_m.unsqueeze(0), z0], dim=1)
        bot_c = torch.stack([z0, z0, z0], dim=1)
        verts = torch.cat([torch.stack([vx, vy, vz], dim=1), top_c, bot_c], dim=0)

        # -- Joints matching SMPLX_TO_MP convention --------------------------
        Z0    = z0[0]
        hh    = height_m
        hip_x = a_hip * 0.65
        sho_x = shoulder_w / 2.0
        el_x  = sho_x + torch.tensor(0.14, dtype=dt, device=dev)
        wr_x  = sho_x + torch.tensor(0.28, dtype=dt, device=dev)
        el_y  = hh * (self.F_SHOULDER - 0.13)
        wr_y  = hh * (self.F_SHOULDER - 0.28)

        jnts = [None] * 22
        jnts[15] = torch.stack([Z0,          hh*self.F_CHIN,     Z0])  # nose
        jnts[16] = torch.stack([-sho_x,      hh*self.F_SHOULDER, Z0])  # L_shoulder
        jnts[17] = torch.stack([ sho_x,      hh*self.F_SHOULDER, Z0])  # R_shoulder
        jnts[18] = torch.stack([-el_x,       el_y,               Z0])  # L_elbow
        jnts[19] = torch.stack([ el_x,       el_y,               Z0])  # R_elbow
        jnts[20] = torch.stack([-wr_x,       wr_y,               Z0])  # L_wrist
        jnts[21] = torch.stack([ wr_x,       wr_y,               Z0])  # R_wrist
        jnts[1]  = torch.stack([-hip_x,      hh*self.F_HIP,      Z0])  # L_hip
        jnts[2]  = torch.stack([ hip_x,      hh*self.F_HIP,      Z0])  # R_hip
        jnts[4]  = torch.stack([-hip_x*0.55, hh*self.F_KNEE,     Z0])  # L_knee
        jnts[5]  = torch.stack([ hip_x*0.55, hh*self.F_KNEE,     Z0])  # R_knee
        jnts[7]  = torch.stack([-hip_x*0.40, hh*self.F_ANKLE,    Z0])  # L_ankle
        jnts[8]  = torch.stack([ hip_x*0.40, hh*self.F_ANKLE,    Z0])  # R_ankle
        for i in range(22):
            if jnts[i] is None:
                jnts[i] = torch.zeros(3, dtype=dt, device=dev)
        joints_3d = torch.stack(jnts, dim=0)  # (22, 3)

        return _BodyModelOutput(
            vertices = verts.unsqueeze(0),        # (1, V, 3)
            joints   = joints_3d.unsqueeze(0),    # (1, 22, 3)
            faces    = self._faces_np,
        )


