"""## Cell 8 — Scale Estimator"""

class ScaleEstimator:
    """Compute cm-per-pixel scale from body keypoints or an A4 reference object."""
    A4_HEIGHT_CM = 29.7
    A4_WIDTH_CM  = 21.0

    def compute(
        self,
        kpts: Dict[str, Tuple[float, float]],
        image_shape: Tuple[int, int],
        height_cm: float,
        reference_image: Optional[np.ndarray] = None,
    ) -> Tuple[float, bool]:
        H, W    = image_shape
        y_nose  = kpts.get('nose',    (W / 2, 0))[1]
        y_l_ank = kpts.get('L_ankle', (W / 2, H * 0.95))[1]
        y_r_ank = kpts.get('R_ankle', (W / 2, H * 0.95))[1]
        y_ankle = (y_l_ank + y_r_ank) / 2.0
        pixel_h = max(abs(y_ankle - y_nose), 20.0)

        if reference_image is not None:
            ref_scale = self._detect_reference_object(reference_image)
            if ref_scale is not None:
                log.info('Reference object detected: scale = %.4f cm/px', ref_scale)
                return ref_scale, True

        scale = height_cm / pixel_h
        log.info('Height-only scale: %.4f cm/px  (pixel_h=%.1fpx)', scale, pixel_h)
        return scale, False

    def _detect_reference_object(self, img: np.ndarray) -> Optional[float]:
        gray    = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        blurred = cv2.GaussianBlur(gray, (5, 5), 0)
        edges   = cv2.Canny(blurred, 30, 100)
        cnts, _ = cv2.findContours(edges, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        h_img, w_img = img.shape[:2]
        best, best_score = None, 0.0
        for c in cnts:
            area = cv2.contourArea(c)
            if area < h_img * w_img * 0.01:
                continue
            peri   = cv2.arcLength(c, True)
            approx = cv2.approxPolyDP(c, 0.02 * peri, True)
            if len(approx) != 4:
                continue
            rect   = cv2.minAreaRect(approx)
            rw, rh = sorted(rect[1])
            if rh < 1:
                continue
            aspect = rw / rh
            if 0.65 < aspect < 0.76:
                score = area / (h_img * w_img)
                if score > best_score:
                    best_score, best = score, rh
        if best is not None and best_score > 0.02:
            return self.A4_HEIGHT_CM / best
        return None

print('ScaleEstimator defined.')

"""## Cell 9 -- ANSUR II Shape Prior

Maps body measurements directly to CPBM beta parameters using ANSUR II population
statistics. Because CPBM betas have a direct physical interpretation (height,
chest girth, waist girth, hip girth, shoulder width, depth ratio), the prior is
a simple z-score transform -- no model sampling or Ridge regression needed.

"""

class ANSURShapePrior:
    """
    Maps body measurements -> CPBM beta warm-start using ANSUR II statistics.

    CPBM beta interpretation:
      b[0] height scale      b[1] chest girth     b[2] waist girth
      b[3] hip girth         b[4] shoulder width  b[5] torso depth ratio

    The prior z-scores each measurement against ANSUR II population norms.
    No model sampling, no Ridge regression, no external weights required.
    """

    N_BETAS = 6

    # ANSUR II 50th-percentile mixed-gender reference (SI units)
    REF = {
        'height_m':   1.720,
        'chest_c_m':  0.974,
        'waist_c_m':  0.839,
        'hip_c_m':    0.967,
        'shoulder_m': 0.430,
    }

    # Beta sensitivity (metres per unit beta).
    # Must match ParametricBodyModel.BETA_SENS exactly.
    SENS = [0.05, 0.04, 0.04, 0.04, 0.02, 0.05]

    def __init__(self, ansur_df=None, smplx_model=None):
        """
        ansur_df    : optional pd.DataFrame to refine REF medians from ANSUR II data.
        smplx_model : accepted but ignored (kept for API compatibility).
        """
        self.is_fitted = True  # always ready -- no external model needed
        if ansur_df is not None:
            self._fit_from_ansur(ansur_df)
        log.info('[ANSURShapePrior] Ready (ANSUR-data refinement: %s)', ansur_df is not None)

    def _find_col(self, df, candidates):
        cols_lower = {c.lower().strip(): c for c in df.columns}
        for cand in candidates:
            if cand in cols_lower:
                return df[cols_lower[cand]]
        return None

    @staticmethod
    def _to_cm(s):
        med = s.dropna().median()
        return s * (0.1 if med > 300 else 1.0 if med > 50 else 100.0)

    def _fit_from_ansur(self, df):
        """Update REF dict from ANSUR II CSV medians."""
        try:
            stature  = self._find_col(df, ['stature','heightmm','height_mm','height'])
            chest    = self._find_col(df, ['chestcircumference','chest_circ','chestgirth','chest'])
            waist    = self._find_col(df, ['waistcircumference','naturalwaistcircumference','waistgirth','waist'])
            hip      = self._find_col(df, ['buttockcircumference','buttock_circ','seatcircumference','hipsgirth','hip'])
            shoulder = self._find_col(df, ['biacromialbreath','biacromialbreedth','shoulderwidth','shoulderbreadth'])
            if stature  is not None: self.REF['height_m']   = float(self._to_cm(stature.dropna()).median())  / 100.0
            if chest    is not None: self.REF['chest_c_m']  = float(self._to_cm(chest.dropna()).median())    / 100.0
            if waist    is not None: self.REF['waist_c_m']  = float(self._to_cm(waist.dropna()).median())    / 100.0
            if hip      is not None: self.REF['hip_c_m']    = float(self._to_cm(hip.dropna()).median())      / 100.0
            if shoulder is not None: self.REF['shoulder_m'] = float(self._to_cm(shoulder.dropna()).median()) / 100.0
            log.info('[ANSURShapePrior] REF updated from ANSUR II: %s',
                     {k: f"{v:.3f}" for k, v in self.REF.items()})
        except Exception as e:
            log.warning('[ANSURShapePrior] Could not update REF from ANSUR: %s', e)

    def predict_betas(self, height_cm: float, chest_cm: float = 97.4,
                      waist_cm: float = 83.9, hip_cm: float = 96.7) -> np.ndarray:
        """Return beta warm-start from body measurements (all in centimetres)."""
        b = np.zeros(self.N_BETAS, dtype=np.float32)
        b[0] = (height_cm / 100.0 - self.REF['height_m'])  / self.SENS[0]
        b[1] = (chest_cm  / 100.0 - self.REF['chest_c_m']) / self.SENS[1]
        b[2] = (waist_cm  / 100.0 - self.REF['waist_c_m']) / self.SENS[2]
        b[3] = (hip_cm    / 100.0 - self.REF['hip_c_m'])   / self.SENS[3]
        # b[4] shoulder and b[5] depth default to 0 (population mean)
        return np.clip(b, -3.0, 3.0)

