class VisionPreprocessor:
    """
    Tier 0: person crop + CLAHE contrast enhancement.

    Person detector: torchvision SSDLite320 MobileNetV3-Large
    -------------------------------------------------------
    * Licence   : Apache 2.0  (commercially free, no restrictions)
    * Weights   : ~28 MB, auto-downloaded from torchvision on first run
    * Backend   : pure PyTorch -- no extra pip install required
    * COCO class: 1 = person

    Performance is comparable to YOLOv8n on full-body, well-lit photos.
    Falls back gracefully to the full image if no person is detected.
    """

    PERSON_CLASS = 1          # COCO label index for 'person'
    SCORE_THRESH = 0.50       # minimum detection confidence
    MARGIN_FRAC  = 0.05       # bounding-box margin as fraction of box size

    def __init__(self):
        log.info('[Tier 0] Loading SSDLite320-MobileNetV3 for person detection...')
        self._has_detector = False
        try:
            from torchvision.models.detection import (
                ssdlite320_mobilenet_v3_large,
                SSDLite320_MobileNet_V3_Large_Weights,
            )
            weights = SSDLite320_MobileNet_V3_Large_Weights.COCO_V1
            self._detector  = ssdlite320_mobilenet_v3_large(weights=weights).to(DEVICE)
            self._detector.eval()
            self._transform = weights.transforms()
            self._has_detector = True
            log.info('[Tier 0] SSDLite320-MobileNetV3 ready.')
        except Exception as e:
            log.warning('[Tier 0] SSDLite not available (%s). Will use full image.', e)
        self.clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))

    @torch.no_grad()
    def _detect_person_bbox(self, img_bgr: np.ndarray):
        """
        Run SSDLite320 on a BGR numpy image.
        Returns (x1, y1, x2, y2) of the largest high-confidence person box,
        or None if no person is found.
        """
        import torchvision.transforms.functional as TF
        from PIL import Image as _PILImage

        h, w = img_bgr.shape[:2]
        rgb_pil = _PILImage.fromarray(cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB))
        inp = self._transform(rgb_pil).unsqueeze(0).to(DEVICE)

        preds = self._detector(inp)[0]
        boxes  = preds['boxes'].cpu().numpy()    # (N, 4) xyxy
        labels = preds['labels'].cpu().numpy()   # (N,)
        scores = preds['scores'].cpu().numpy()   # (N,)

        mask = (labels == self.PERSON_CLASS) & (scores >= self.SCORE_THRESH)
        if not mask.any():
            return None

        person_boxes = boxes[mask]
        areas = ((person_boxes[:, 2] - person_boxes[:, 0]) *
                 (person_boxes[:, 3] - person_boxes[:, 1]))
        best  = person_boxes[np.argmax(areas)]
        return best   # (x1, y1, x2, y2)

    def crop_and_enhance(
        self,
        img: np.ndarray,
        target_size: Tuple[int, int] = (512, 768),
    ) -> Tuple[np.ndarray, Tuple[int, int, int, int]]:
        h, w    = img.shape[:2]
        x1, y1, x2, y2 = 0, 0, w, h

        if self._has_detector:
            bbox = self._detect_person_bbox(img)
            if bbox is not None:
                bx1, by1, bx2, by2 = map(int, bbox)
                mx  = int((bx2 - bx1) * self.MARGIN_FRAC)
                my  = int((by2 - by1) * self.MARGIN_FRAC)
                x1  = max(0, bx1 - mx)
                y1  = max(0, by1 - my)
                x2  = min(w, bx2 + mx)
                y2  = min(h, by2 + my)
                frac = (x2 - x1) * (y2 - y1) / (h * w)
                if frac < InputValidator.MIN_PERSON_FRACTION:
                    log.warning('Person occupies only %.1f%% of image.', 100 * frac)
            else:
                log.warning('No person detected by SSDLite -- using full image.')

        crop  = img[y1:y2, x1:x2]
        gray  = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
        norm  = cv2.cvtColor(self.clahe.apply(gray), cv2.COLOR_GRAY2BGR)
        final = cv2.resize(norm, target_size)
        return final, (x1, y1, x2, y2)

